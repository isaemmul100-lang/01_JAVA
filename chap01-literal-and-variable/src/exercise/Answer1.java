package exercise;

public class Answer1 {

    public static void main(String[] args) {

        /*
         * 문제 1. 여러 종류의 리터럴 출력
         *
         * 다음 값을 알맞은 형태의 리터럴로 직접 출력한다.
         * - 문자열 Java
         * - 정수 100
         * - 실수 3.14
         * - 문자 A
         * - 논리값 true
         *
         * 실행 결과
         * Java
         * 100
         * 3.14
         * A
         * true
         */

        String st = "JAVA";
        System.out.println(st);
        int inum = 100;
        System.out.println(inum);
        double dnum = 3.14;
        System.out.println(dnum);
        char ch = 'A';
        System.out.println(ch);
        boolean bool = true;
        System.out.println(bool);

    }

}
