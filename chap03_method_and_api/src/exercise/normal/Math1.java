package exercise.normal;
import java.lang.Math;

public class Math1 {

    public static void main(String[] args) {
        System.out.println("max(20, 35) : " + Math.max(20, 35));
        System.out.println("min(20, 35) : " + Math.min(20, 35));
        System.out.println("abs(-17) : " + Math.abs(-17));
        System.out.println("pow(2, 10) : " + (double) Math.pow(2, 10));
        System.out.println("sqrt(81) : " + (double) Math.sqrt(81));
    }

}
